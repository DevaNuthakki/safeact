@dataclass(frozen=True)
class Environment:
    """One lifecycle schema and the login roles that operate it."""

    schema: str
    owner: str
    api: str
    worker: str
    recoverer: str
    advancer: str
    mcp: str

    @classmethod
    def demo(cls):
        return cls(
            schema=DEMO_SCHEMA,
            owner="safeact_demo_owner",
            api="safeact_demo_api",
            worker="safeact_demo_worker",
            recoverer="safeact_demo_recoverer",
            advancer="safeact_demo_advancer",
            mcp="safeact_demo_mcp",
        )

    @classmethod
    def disposable(cls, suffix):
        """A throwaway environment for tests; same build, other names."""

        base = "safeact_dm_it_" + suffix
        return cls(
            schema="safeact_it_" + suffix,
            owner=base + "_owner",
            api=base + "_api",
            worker=base + "_worker",
            recoverer=base + "_recoverer",
            advancer=base + "_advancer",
            mcp=base + "_mcp",
        )

    def __post_init__(self):
        if self.schema == "public":
            raise ValueError("The demo never rebuilds public")
        lsql._schema(self.schema)
        for role in self.roles:
            lsql._role(role)

    @property
    def login_roles(self):
        return (self.api, self.worker, self.recoverer, self.advancer,
                self.mcp)

    @property
    def roles(self):
        return (self.owner,) + self.login_roles


def _require_local(admin):
    info = admin.info
    if info.host not in ("127.0.0.1", "localhost") or info.dbname != (
        "safeact_dev"
    ):
        raise RuntimeError("STOP: local development database required")


def _refuse_privileged(admin, env):
    privileged = admin.execute(
        "SELECT rolname FROM pg_roles WHERE rolname = ANY(%s) "
        "AND (rolsuper OR rolcreaterole OR rolcreatedb "
        "OR rolreplication OR rolbypassrls)",
        (list(env.roles),),
    ).fetchall()
    if privileged:
        raise RuntimeError("STOP: a demo role name is held by a privileged role")


def teardown_statements(admin, env):
    existing = {
        row[0] for row in admin.execute(
            "SELECT rolname FROM pg_roles WHERE rolname = ANY(%s)",
            (list(env.roles),),
        )
    }
    statements = [sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
        sql.Identifier(env.schema)
    )]
    for role in env.roles:
        if role in existing:
            statements += [
                sql.SQL("DROP OWNED BY {}").format(sql.Identifier(role)),
                sql.SQL("DROP ROLE {}").format(sql.Identifier(role)),
            ]
    return statements


def build_statements(env, passwords):
    statements = [sql.SQL(
        "CREATE ROLE {} NOLOGIN NOINHERIT NOSUPERUSER "
        "NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS"
    ).format(sql.Identifier(env.owner))]
    statements += [
        sql.SQL(
            "CREATE ROLE {} LOGIN NOINHERIT NOSUPERUSER "
            "NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS "
            "PASSWORD {}"
        ).format(
            sql.Identifier(role),
            sql.Literal(scram_verifier(passwords[role])),
        )
        for role in env.login_roles
    ]
    statements.append(sql.SQL("CREATE SCHEMA {}").format(
        sql.Identifier(env.schema)
    ))
    statements += schema_statements(
        env.schema,
        owner=env.owner,
        workers=(env.worker,),
        recoverers=(env.recoverer,),
        advancers=(env.advancer,),
        apis=(env.api,),
        mcps=(env.mcp,),
    )
    # The API role handles passwords and session secrets, the MCP role
    # agent keys, as bound parameters: their sessions never log
    # statements or parameters.
    statements += role_logging_statements(env.api)
    statements += role_logging_statements(env.mcp)
    for role in env.login_roles:
        statements += application_role_statements(role)
    return statements


def seed_accounts(admin, env, accounts=DEMO_ACCOUNTS):
    """Create the synthetic demo principals; return their passwords."""

    passwords = {}
    for account in accounts:
        password = (
            secrets.token_urlsafe(18) if account.kind == "human" else None
        )
        create_principal(
            admin, env.schema,
            tenant_id=account.tenant_id,
            username=account.username,
            display_name=account.display_name,
            kind=account.kind,
            roles=account.roles,
            password=password,
            principal_id=account.principal_id,
            grants=account.grants,
        )
        if password is not None:
            passwords[account.username] = password
    return passwords


def rebuild(admin, env, *, profiles=MOCK_PROFILES, accounts=()):
    """Drop and recreate ``env`` in one transaction.

    Returns the login-role passwords and the seeded account passwords.
    """

    if not admin.autocommit:
        raise RuntimeError("Rebuild needs an autocommit administrator")
    _require_local(admin)
    _refuse_privileged(admin, env)

    passwords = {role: secrets.token_urlsafe(32) for role in env.login_roles}

    # Sessions held by the old roles would block DROP ROLE.
    admin.execute(
        "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
        "WHERE usename = ANY(%s) AND pid <> pg_backend_pid()",
        (list(env.roles),),
    )

    with admin.transaction():
        admin.execute("SET LOCAL lock_timeout = '5s'")
        for statement in teardown_statements(admin, env):
            admin.execute(statement)
        for statement in build_statements(env, passwords):
            admin.execute(statement)
        for profile in profiles:
            for statement, params in register_statements(env.schema, profile):
                admin.execute(statement, params)
        registered = {(p.connector_id, p.version) for p in profiles}
        for connector_id, version in REVIEWED_CONTRACTS:
            if (connector_id, version) not in registered:
                continue
            admin.execute(sql.SQL(
                "INSERT INTO {}.safeact_contract_review_policies "
                "(connector_id, version, retry_requires_approval) "
                "VALUES (%s, %s, true)"
            ).format(sql.Identifier(env.schema)), (connector_id, version))
        account_passwords = seed_accounts(admin, env, accounts)

    return passwords, account_passwords


def issue_agent_keys(admin, env, accounts=DEMO_ACCOUNTS):
    """Issue one agent key per service account; return them by username.

    A separate transaction after the rebuild. Keys are plaintext only in
    the returned mapping (and the mode-600 credentials file).
    """

    keys = {}
    with admin.transaction():
        for account in accounts:
            if account.kind != "service" or not account.scopes:
                continue
            principal_id = admin.execute(sql.SQL(
                "SELECT principal_id FROM {}.safeact_principals "
                "WHERE username = %s"
            ).format(sql.Identifier(env.schema)),
                (account.username,)).fetchone()[0]
            keys[account.username] = issue_agent_key(
                admin, env.schema, principal_id=principal_id,
                scopes=account.scopes, label="demo", created_by="bootstrap",
            ).key
    return keys


def credential_lines(env, passwords, account_passwords=None):
    lines = {
        "SAFEACT_DEMO_SCHEMA": env.schema,
        "SAFEACT_DEMO_API_ROLE": env.api,
        "SAFEACT_DEMO_WORKER_ROLE": env.worker,
        "SAFEACT_DEMO_RECOVERER_ROLE": env.recoverer,
        "SAFEACT_DEMO_ADVANCER_ROLE": env.advancer,
        "SAFEACT_DEMO_MCP_ROLE": env.mcp,
        "SAFEACT_DEMO_API_PASSWORD": passwords[env.api],
        "SAFEACT_DEMO_WORKER_PASSWORD": passwords[env.worker],
        "SAFEACT_DEMO_RECOVERER_PASSWORD": passwords[env.recoverer],
        "SAFEACT_DEMO_ADVANCER_PASSWORD": passwords[env.advancer],
        "SAFEACT_DEMO_MCP_PASSWORD": passwords[env.mcp],
    }
    for username, password in (account_passwords or {}).items():
        lines[username] = password
    return lines


def write_credentials(path, lines):
    """Atomically replace ``path`` with a mode-600 credentials file."""

    path = Path(path)
    text = HEADER + (
        f"# Generated {datetime.now(timezone.utc).isoformat()}\n"
    ) + "".join(f"{key}={value}\n" for key, value in lines.items())

    fd, temporary = tempfile.mkstemp(
        prefix=".demo-credentials-", dir=path.parent
    )
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def read_credentials(path=CREDENTIALS):
    path = Path(path)
    if not path.is_file():
        raise RuntimeError(
            "Missing demo credentials: run python -m deploy.demo.bootstrap"
        )
    if path.stat().st_mode & 0o077:
        raise RuntimeError("Unsafe demo credential permissions")

    settings = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or key in settings:
            raise RuntimeError("Invalid demo credentials file")
        settings[key] = value
    return settings


def stripe_demo_accounts(fixtures, accounts=DEMO_ACCOUNTS):
    """The north requester may also refund the two Stripe test intents."""

    from dataclasses import replace

    from deploy.demo.stripe_demo import grants

    return tuple(
        replace(account, grants=account.grants + grants(fixtures))
        if account.username == "demo-north-requester" else account
        for account in accounts
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--credentials", type=Path, default=CREDENTIALS,
        help="where to write the generated demo credentials (mode 600)",
    )
    parser.add_argument(
        "--stripe", action="store_true",
        help="also register the Stripe test-mode demo contract and grant "
             "demo-north-requester the PaymentIntents in .demo-stripe.json "
             "(no Stripe call here; see deploy/demo/stripe_demo.py)",
    )
    args = parser.parse_args(argv)

    env = Environment.demo()
    profiles, demo_accounts = DEMO_PROFILES, DEMO_ACCOUNTS
    if args.stripe:
        from deploy.demo import stripe_demo

        profiles = DEMO_PROFILES + (stripe_demo.PROFILE,)
        demo_accounts = stripe_demo_accounts(stripe_demo.read_fixtures())
    with psycopg.connect(**local_admin_settings(), autocommit=True) as admin:
        passwords, accounts = rebuild(
            admin, env, profiles=profiles, accounts=demo_accounts
        )
        agent_keys = issue_agent_keys(admin, env, demo_accounts)
    write_credentials(
        args.credentials,
        credential_lines(env, passwords, {**accounts, **agent_keys}),
    )

    print(
        f"Rebuilt {env.schema} at {lsql.HEAD_REVISION} with "
        f"{len(profiles)} demo-scaled contract versions across "
        f"{len({p.connector_id for p in profiles})} connectors"
        f"{' (incl. Stripe test mode)' if args.stripe else ''}. "
        f"{len(accounts)} demo sign-ins, {len(agent_keys)} agent keys. "
        f"DEMO ONLY: credentials in "
        f"{args.credentials} (mode 600)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
