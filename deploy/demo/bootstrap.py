"""Rebuild the local ``safeact_demo`` environment from scratch.

    .venv/bin/python -m deploy.demo.bootstrap

One idempotent command (blueprint A12). In a single transaction on the
local development database it drops the ``safeact_demo`` schema and its
demo roles if present, recreates them at the lifecycle head with the
three mock connector contracts, and wires each component's login role.
Running it twice gives the same end state.

DEMO ONLY. Mock connectors and synthetic data; nothing here reaches a
real provider (``--stripe`` only registers the optional Stripe test-mode
contract and grants; deploy/demo/stripe_demo.py). ``public`` is never touched and stays deny-only (no
registered contracts). Fresh role passwords are generated on every run
and written to ``.demo-credentials`` (mode 600, gitignored) only after
the rebuild commits; they are sent to PostgreSQL as SCRAM verifiers, so
no plaintext role password appears in any statement.
"""

